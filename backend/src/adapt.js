export function adaptActivity(a, condition) {
  const c = CONDITIONS[condition];
  if (!c) return null;
  const stages = a.stages.map((s, i) => {
    const extra = [`התאמה (${c.label}): ${c.tips[i]}`];
    if (MOVE.test(s.content)) extra.push(c.move);
    return { ...s, content: `${s.content}\n${extra.join("\n")}`.slice(0, 3000) };
  });
  const joinSafe = (base, add) => `${base} ${add}`.slice(0, 1000);
  return {
    title: `${a.title} (גרסת ${c.label})`.slice(0, 120),
    equipment: `${a.equipment}. בנוסף: ${c.equipment}`.slice(0, 500),
    safetyNotes: joinSafe(a.safetyNotes, c.safety),
    tags: [...new Set([...a.tags, `גרסת ${c.label}`])].slice(0, 20),
    stages,
  };
}
