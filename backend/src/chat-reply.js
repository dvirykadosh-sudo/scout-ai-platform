export function checkReply(draft, { where = "private", intent = "", hour = null, kid = "n" } = {}) {
  const text = String(draft ?? "").trim();
  const items = [];
  const add = (level, code, msg) => items.push({ level, code, text: msg });
  if (!text) return { ok: false, items: [{ level: "warn", code: "empty", text: "אין טיוטה לבדיקה." }], stats: { words: 0, emojis: 0 } };
  const words = countWords(text);
  const emojis = (text.match(EMOJI_COUNT) || []).length;
  if (SECRECY.test(text)) add("red", "secrecy", "הבטחה לסודיות או בקשה להסתיר מההורים. זה אסור: אם יש בשיחה משהו מדאיג, אתם חייבים להעביר הלאה. נסחו כך: \"אני לא יכול/ה להבטיח שזה יישאר בינינו, כי אכפת לי ממך.\"");
  if (ALONE.test(text)) add("red", "alone", "הצעה להיפגש לבד עם קטין. נפגשים בנוכחות מדריך נוסף, במקום פתוח ועם ידיעת ההורים, לפי נוהל התנועה.");
  if (MINIMIZE.test(text)) add("warn", "minimize", "ניסוח שמקטין את התחושה (\"אל תדאג\", \"זה לא נורא\"). החניך שומע \"אל תרגיש\". אמרו מה שמעתם: \"נשמע שזה היה לא נעים\".");
  if (BLAME.test(text)) add("warn", "blame", "ניסוח מאשים (\"אתה תמיד\", \"אף פעם\"). תארו מה קרה ומה אתם צריכים: \"בפעולה האחרונה הגעת באיחור. מה היה עוזר לך להגיע בזמן?\"");
  if (BUT_AFTER.test(text)) add("warn", "but", "\"אבל\" אחרי הבנה מבטל אותה. החליפו ב\"וגם\" או פצלו לשתי הודעות.");
  if (where === "group") {
    if (SENSITIVE_PUBLIC.test(text)) add("red", "public-private", "ההודעה בקבוצה נוגעת בנושא אישי. נושאים אישיים רק בפרטי.");
    if (/(?:חניך [א-ת]'|@)/.test(text) && /(?:אתה|את|שוב|תפסיק|תפסיקי|די)/.test(text)) add("warn", "shaming", "תיקון של חניך מסוים מול הקבוצה מביך אותו. כתבו לו בפרטי, ובקבוצה הודעה כללית.");
    if (words > 70) add("tip", "long-group", "הודעה ארוכה בקבוצה לא נקראת עד הסוף. שמרו על עד 60 מילים והדגישו את המידע החשוב (*כך*).");
  } else if (words > 60) add("tip", "long", `ההודעה ארוכה (${words} מילים) לצ'אט. שקלו לקצר, או להציע שיחה קולית.`);
  const excl = (text.match(/!/g) || []).length;
  if (excl >= 3) add("tip", "excl", "הרבה סימני קריאה נשמעים כצעקה בטקסט. השאירו אחד.");
  if (emojis > 4) add("tip", "emoji", `${emojis} אימוג'ים. שניים-שלושה מספיקים.`);
  if (hour !== null && (hour >= 22 || hour < 6)) add("tip", "late", "השעה מאוחרת. אם זה לא דחוף, שמרו כטיוטה ושלחו בבוקר. חניכים לומדים מכם איך נראות שעות פנאי.");
  if (["emotional", "conflict"].includes(intent) && !/\?/.test(text)) add("tip", "ask", "בשיחה רגישה כדאי לסיים בשאלה פתוחה אחת, כמו \"רוצה לספר לי יותר?\" או בהצעה לשיחה.");
  const cl = findCliches(text).items.filter((i) => i.kind === "cliche");
  if (cl.length) add("tip", "cliche", `נשמע כמו נאום: ${cl.slice(0, 3).map((c) => `"${c.text}"`).join(", ")}. בצ'אט מדברים קצר ופשוט.`);
  if (/[א-ת]/.test(text) && /(?<![א-ת])(?:הנך|הינך|אשר|לפיכך|הרינו)(?![א-ת])/.test(text)) add("tip", "formal", "שפה רשמית מדי לחניך. כתבו כמו שאתם מדברים.");
  if (kid !== "n" && !items.some((i) => i.level === "red" || i.level === "warn")) add("ok", "ok", "לא מצאנו בעיה בניסוח.");
  const bad = items.some((i) => i.level === "red" || i.level === "warn");
  return { ok: !bad, items, stats: { words, emojis }, note: "הבדיקה מבוססת על דפוסים. היא לא מחליפה קריאה אחרונה שלכם לפני שליחה." };
}

