/**
 * מציע תגובות לפי הכוונה שזוהתה. ללא טקסט אמיתי של החניך: placeholders בסוגריים מרובעים.
 * @param {object} o intent, text (של החניך, לבדיקת איחור/מחלה), name, kid ('m'|'f'|'n'), guide ('m'|'f'|'n'), voice {say,never}
 */
export function replySuggestions({ intent = "general", text = "", name = "", kid = "n", guide = "n", voice = {} } = {}) {
  const key = TEMPLATES[intent] ? intent : "general";
  const nm = name ? ` ${name.trim().slice(0, 30)}` : "";
  const gender = { kid, guide };
  const variants = TEMPLATES[key](nm, text).map((x) => {
    const t = inflect(x.text, gender);
    const dict = dictCheck(t, voice);
    return { ...x, text: t, slots: slotsOf(t), words: countWords(t), neverHits: dict.neverHits || [], cliches: findCliches(t).total };
  });
  return {
    intent: key,
    label: INTENT_LABEL[key] || "הודעה",
    variants,
    avoid: AVOID[key] || AVOID.general,
    tip: MOVE_TO_VOICE.has(key) ? "כדאי להעביר את זה לשיחת טלפון או לשיחה פנים אל פנים. טקסט מתפרש קר יותר ממה שהתכוונתם." : null,
  };
}

