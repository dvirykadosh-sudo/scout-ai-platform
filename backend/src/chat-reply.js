const joinForms = (m, f) => {
  if (m === f) return m;
  let i = 0;
  while (i < m.length && i < f.length && m[i] === f[i]) i++;
  const p = m.slice(0, i), a = m.slice(i), b = f.slice(i);
  if (!a) return `${p}/${b}`;
  if (!b) return `${p}/${a}`;
  return `${m}/${f}`;
};
/** <k:זכר|נקבה> לפי מגדר החניך, <g:זכר|נקבה> לפי מגדר המדריך. בלי מגדר: "בוא/י". */
export function inflect(text, { kid = "n", guide = "n" } = {}) {
  return String(text).replace(/<([kg]):([^|>]+)\|([^>]+)>/g, (_, w, m, f) => {
    const g = w === "k" ? kid : guide;
    return g === "m" ? m : g === "f" ? f : joinForms(m, f);
  });
}
