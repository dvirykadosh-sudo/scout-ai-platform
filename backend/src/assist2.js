const stripMin = (s) => s.replace(/[.,]?\s*\d{1,3}\s*(?:דקות|דקה|דק['׳]?)\.?/g, "").trim();
const ASK = /\?/;

/** תסריט לפי דקות: מה אומרים, מה עושים, שאלות, למה לשים לב ומעבר לשלב הבא. */
export function buildScript(raw) {
  const a = analyze(raw);
  const topic = topicOf(a.title);
  const safety = lineAfter(raw, ["בטיחות"]);
  const equipment = lineAfter(raw, ["ציוד"]);
  let at = 0;
  const filled = a.stages.map((s, i) => ({ s, i })).filter((x) => x.s.filled);
  const steps = filled.map(({ s, i }, n) => {
    const mins = s.minutes || DEFAULT_MIN[i];
    const sents = sentencesOf(stripMin(s.content));
    const ask = sents.filter((x) => ASK.test(x));
    const doIt = sents.filter((x) => !ASK.test(x));
    const watch = [WATCH[i]];
    if (i === 1 && safety) watch.unshift(`בטיחות: ${safety}`);
    const step = {
      stage: s.name,
      from: at,
      to: at + mins,
      minutes: mins,
      say: [OPENERS[i](topic)],
      do: doIt,
      ask,
      watch,
      transition: n < filled.length - 1 ? TRANSITIONS[filled[n + 1].i] : "תודה לכולם. נתראה בפעם הבאה, היה נכון.",
    };
    at += mins;
    return step;
  });
  return { title: a.title, totalMinutes: at, equipment, safety, planB: a.planB, steps };
}

// ───────────── 69. הערות אחרי הפעולה ─────────────

const CUES = {
  worked: /(?:עבד|הצליח|אהבו|התלהב|נהנ|מעולה|מצוין|שיתפו פעולה|היה כיף|הרבה אנרגיה|התחברו)/,
  change: /(?:לא עבד|לא הצליח|בפעם הבאה|צריך לשנות|לשנות|חסר|בעיה|הפריע|היה קשה|לא הבינו|משעמם|שעמום|נתקע|התפזר)/,
  timing: /(?:דקות|זמן|ארוך|קצר|נגמר|איחור|מהר מדי|לאט|התארך|הספקנו)/,
  group: /(?:חניכים|הקבוצה|ילדים|בנות|בנים|שקט|רעש|מאחרים|הגיעו|נעדר|הגיעה)/,
  ideas: /(?:רעיון|כדאי|נסו|נסה|להוסיף|הצעה|אפשר היה)/,
};
const STAGE_WORDS = [
  [0, /(?:פתיחה|פתחנו|בתחילת)/],
  [1, /(?:משחק|מירוץ|תחנות|תחרות)/],
  [2, /(?:צופיות|קשר|מיומנות|מעשי)/],
  [3, /(?:דיון|שיחה|שאלה)/],
  [4, /(?:סיכום|סגירה|סיום)/],
];
const LONG = /(?:לקח יותר|התארך|ארוך מדי|ארוך|לא הספקנו|חרגנו|נגמר באיחור|לא הסתיים בזמן|חסר זמן)/;
const SHORT = /(?:נגמר מהר|קצר מדי|הסתיים מהר|נשאר זמן|היה זמן פנוי)/;

/** מפרק הערה חופשית (כתובה או מוכתבת) לקטגוריות, ומציע מה לשנות בטיוטה. */
export function parseReflection(text) {
  const buckets = { worked: [], change: [], timing: [], group: [], ideas: [], other: [] };
  const draftTips = [];
  for (const s of sentencesOf(text)) {
    const t = norm(s);
    let any = false;
    for (const k of Object.keys(CUES)) {
      if (CUES[k].test(t)) {
        buckets[k].push(s);
        any = true;
      }
    }
    if (!any) buckets.other.push(s);
    if (CUES.timing.test(t)) {
      const stage = STAGE_WORDS.find(([, re]) => re.test(t));
      const name = stage ? STAGE_NAMES[stage[0]] : null;
      if (LONG.test(t)) draftTips.push(name ? `ב"${name}" הזמן לא הספיק. הוסיפו דקות או קצרו את התוכן.` : "הפעולה התארכה. קצרו שלב אחד או הגדילו את משך הפעולה.");
      else if (SHORT.test(t)) draftTips.push(name ? `ב"${name}" נשאר זמן. אפשר להוסיף סבב או להקטין את הזמן.` : "נשאר זמן בפעולה. אפשר להוסיף סבב דיון או משחק נוסף.");
    }
    if (/לא הבינו/.test(t)) draftTips.push("החניכים לא הבינו. הוסיפו דוגמה או הדגמה לפני שמתחילים.");
  }
  return { ...buckets, draftTips: [...new Set(draftTips)].slice(0, 4), total: sentencesOf(text).length };
}
