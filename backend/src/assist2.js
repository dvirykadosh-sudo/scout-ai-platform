const STOP = new Set(["שהחניכים", "החניכים", "פעולה", "פעולת", "על", "את", "של", "עם", "כדי", "זה", "לא", "כל", "הם", "היא", "הוא", "אחד", "יבינו"]);
const toks = (s) => new Set((norm(s).match(/[א-ת]{3,}/g) || []).filter((w) => !STOP.has(w)).map((w) => w.replace(/^[והבלמש]{1,2}(?=[א-ת]{3,})/, "")));

function cutAtSentence(text, max = 420) {
  const t = String(text || "").trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max);
  const i = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("? "), cut.lastIndexOf("! "));
  return (i > 80 ? cut.slice(0, i + 1) : cut.replace(/\s+\S*$/, "")).trim();
}

/** רעיונות לשלב מסוים מתוך פעולות פורסמו במאגר, לפי דמיון בנושא, בערך ובשיטות. */
export function inspireFrom(activities, raw, stageParam) {
  const a = analyze(raw);
  let stageIdx = Number.isInteger(stageParam) ? stageParam : a.stages.findIndex((s) => !s.filled);
  if (stageIdx < 0 || stageIdx > 4) stageIdx = 1;
  const draftToks = toks(`${a.title} ${a.value?.text || ""}`);
  const draftMethods = new Set(a.methods.map((m) => m.name));
  const items = [];
  for (const act of activities) {
    const st = act.stages?.[stageIdx];
    if (!st || words(st.content) < 5) continue;
    if (a.title && norm(act.title) === norm(a.title)) continue;
    const titleToks = toks(`${act.title} ${act.leadingValue}`);
    const bodyToks = toks(`${(act.tags || []).join(" ")} ${st.content}`);
    let score = 0;
    const why = [];
    const sharedTitle = [...draftToks].filter((w) => titleToks.has(w));
    const sharedBody = [...draftToks].filter((w) => bodyToks.has(w));
    if (sharedTitle.length) {
      score += sharedTitle.length * 3;
      why.push("נושא או ערך דומה");
    }
    if (sharedBody.length) score += sharedBody.length;
    const sharedMethods = (act.methods || []).filter((m) => draftMethods.has(m.name));
    if (sharedMethods.length) {
      score += sharedMethods.length * 2;
      why.push(`אותה שיטה: ${sharedMethods[0].name}`);
    }
    if (!draftToks.size && !draftMethods.size) score = 1;
    if (score <= 0) continue;
    items.push({ id: act.id, title: act.title, ageGroup: act.ageGroup, durationMin: act.durationMin, stage: STAGE_NAMES[stageIdx], minutes: st.minutes, excerpt: cutAtSentence(st.content), why: why[0] || "רעיון לשלב הזה", score });
  }
  items.sort((x, y) => y.score - x.score || x.id - y.id);
  return { stage: STAGE_NAMES[stageIdx], stageIndex: stageIdx, header: HEADERS[stageIdx], items: items.slice(0, 5).map(({ score, ...r }) => r) };
}

