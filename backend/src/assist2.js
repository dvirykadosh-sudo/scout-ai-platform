// ───────────── 66. ציוד מהטיוטה מול הארון ─────────────

const wordRe = (w) => new RegExp(`(?:^|[^א-ת])${w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?:[^א-ת]|$)`);

/** רשימת הציוד כפי שנכתבה, ציוד שנזכר בטיוטה ולא נכתב, ומה חסר בארון. */
export function gearFromDraft(raw, have = [], extra = "") {
  const text = norm(raw);
  const listedLine = lineAfter(raw, ["ציוד"]);
  const cupboardKnown = have.length > 0 || !!extra.trim();
  const listedMatch = listedLine ? matchCupboard(listedLine, have, extra) : { items: [], missing: [], optionalMissing: [] };
  const listedGroups = new Set();
  if (listedLine) for (const g of GEAR_GROUPS) if (g.words.some((w) => wordRe(norm(w)).test(norm(listedLine)))) listedGroups.add(g.id);
  // מחפשים בגוף הפעולה, לא בשורות המטא
  const body = parseDraft(raw).stages.join("\n");
  const inferred = [];
  for (const g of GEAR_GROUPS) {
    if (listedGroups.has(g.id)) continue;
    const hit = g.words.find((w) => wordRe(norm(w)).test(norm(body)));
    if (hit) inferred.push({ id: g.id, label: g.label, evidence: hit, covered: have.includes(g.id) });
  }
  const listed = listedMatch.items.map((i) => ({ text: i.text, optional: i.optional, covered: i.covered }));
  const missing = [...listedMatch.missing, ...inferred.filter((i) => !i.covered).map((i) => i.label)];
  const parts = [...listed.filter((i) => !i.optional).map((i) => i.text), ...inferred.map((i) => i.label)];
  return {
    listedLine,
    listed,
    inferred,
    missing: cupboardKnown ? missing : [],
    cupboardKnown,
    suggestedLine: parts.length ? `ציוד: ${[...new Set(parts)].join(", ")}` : "",
    hasText: text.trim().length > 0,
  };
}

