/** הצעות להחלפת שיטה שזוהתה בטיוטה, עם משפט מוכן במקום המשפט הנוכחי. */
export function swapOptions(raw, method) {
  const a = analyze(raw);
  const keys = METHOD_KEYS[method] || [];
  let stageIdx = -1;
  let current = "";
  for (let i = 0; i < a.stages.length && !current; i++) {
    for (const s of sentencesOf(a.stages[i].content)) {
      const t = norm(s);
      if (keys.some((k) => has(t, k)) || has(t, method)) {
        stageIdx = i;
        current = s;
        break;
      }
    }
  }
  const topic = topicOf(a.title);
  const mins = (stageIdx >= 0 && a.stages[stageIdx].minutes) || (stageIdx >= 0 ? DEFAULT_MIN[stageIdx] : 15);
  const present = new Set(a.methods.map((m) => m.name));
  const alternatives = (SWAP[method] || [])
    .filter(([n]) => n !== method)
    .map(([name, why]) => {
      const m = METHODS.find((x) => x.name === name);
      const label = stageIdx >= 0 ? HEADERS[stageIdx] : "משחק";
      const line = SWAP_LINE[name](topic, mins).replace(/^משחק:/, `${label}:`);
      return { name, why, already: present.has(name), example: m?.example || "", text: line, sentence: line.replace(/^[^:]+:\s*/, "").replace(/\s*\d+ דקות$/, "").replace(/\.*$/, ".") };
    });
  return { method, found: !!current, stage: stageIdx >= 0 ? STAGE_NAMES[stageIdx] : null, current, alternatives };
}

