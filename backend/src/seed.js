export function seedIfEmpty(db) {
  const count = db.prepare("SELECT COUNT(*) AS c FROM activities").get().c;
  if (count > 0) return 0;
  for (const a of SEED_ACTIVITIES) {
    const last = a.stages[4];
    last.content = `${last.content} ${conclusion(a.leadingValue)}`;
    insertActivity(db, {
      ...a,
      durationMin: a.stages.reduce((s, x) => s + x.minutes, 0),
      tribe: "שבט מעוז",
      battalion: "",
      groupSize: 20,
      conclusionNote: conclusion(a.leadingValue),
      isSeed: true,
    });
  }
  return SEED_ACTIVITIES.length;
}
