/** מוסיף סיפור לשלב קיים (בסוף תוכן השלב). */
export function addStoryToStage(activity, story, stageIndex) {
  const i = Math.min(Math.max(Number(stageIndex) || 0, 0), activity.stages.length - 1);
  const block = `\nסיפור לשילוב (${story.title}): ${story.text}\nשאלה לשיחה: ${story.question}`;
  const stages = activity.stages.map((s, idx) => (idx === i ? { ...s, content: cap(`${s.content}${block}`, 3000) } : s));
  return stages;
}

