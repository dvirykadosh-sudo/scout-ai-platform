const firstSentence = (s, n = 110) => {
  const one = norm(String(s || "").split(/\n/)[0]).split(/(?<=[.!?])\s/)[0];
  return one.length > n ? `${one.slice(0, n - 1).trim()}…` : one;
};

export function activitySummary(a) {
  const v = norm(a.leadingValue) || "ערך השבוע";
  const names = (a.methods || []).map((m) => m.name).slice(0, 3);
  const doing = a.stages[1] ? firstSentence(a.stages[1].content) : "";
  const q = discussionQuestions(a).levels[1].questions[0];
  const sign = [a.instructor, a.tribe].filter(Boolean).join(", ");
  const parents = [
    "שלום להורים,",
    `היום בפעולה (${a.ageGroup}) עסקנו בערך "${v}": ${a.title}.`,
    `הפעולה נמשכה כ-${a.durationMin} דקות${names.length ? ` ושילבה ${names.join(", ")}` : ""}.`,
    doing ? `מה עשינו: ${doing}` : null,
    `אפשר לשאול בבית: ${q}`,
    sign ? `${sign}` : null,
  ].filter(Boolean);
  const leader = [
    `פעולה: ${a.title} (${a.ageGroup}, ${a.durationMin} דקות).`,
    `ערך מוביל: ${v}.`,
    `שלבים: ${a.stages.map((s) => `${s.name} ${s.minutes} דק'`).join(", ")}.`,
    `ציוד: ${a.equipment || "לא צוין"}.`,
    `בטיחות: ${a.safetyNotes || "לא צוין"}`,
  ];
  return { parents: parents.join("\n"), leader: leader.join("\n") };
}

