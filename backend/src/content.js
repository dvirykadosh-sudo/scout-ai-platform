/** הצעות שדרוג לפי הרישום האחרון של המדריך בפעולה. */
export function suggestAfterRun(run, activity) {
  const out = [];
  const seen = new Set();
  const add = (tip, action) => {
    const key = `${action.type}:${action.condition || action.category || action.minutes || ""}`;
    if (seen.has(key) || out.length >= 4) return;
    seen.add(key);
    out.push({ tip, action });
  };
  if (!run) return out;
  if (run.timing === "long") {
    const m = nearestShort(activity.durationMin);
    if (m) add(`הפעולה נמשכה יותר מהמתוכנן. אפשר גרסה של ${m} דקות.`, { type: "shorten", minutes: m, label: `גרסה של ${m} דקות` });
  }
  if (run.timing === "short") add("הפעולה נגמרה מוקדם. כדאי להוסיף שאלות דיון נוספות או משחק חימום.", { type: "questions", label: "שאלות דיון ברמות" });
  if (run.engagement === 1) {
    add("ההשתתפות היתה נמוכה. אפשר להתאים לקבוצה עם הרבה אנרגיה.", { type: "adapt", condition: "restless", label: "התאמה לקבוצה עם הרבה אנרגיה" });
    if (activity.kind !== "peak") add("אפשר גם לשדרג את הפעולה לפעולת שיא, עם רגע מרכזי אחד חזק.", { type: "upgrade-peak", label: "הפוך לפעולת שיא" });
  }
  const text = `${run.worked || ""} ${run.changeNext || ""} ${run.notes || ""}`;
  for (const r of KEYWORD_RULES) if (r.re.test(text)) add(r.tip, r.action);
  return out;
}

/** מה עבד הכי טוב אצל המדריך, לפי הדירוגים בהפעלות. מחזיר רק כשיש מספיק נתונים. */
export function learnFromRuns(db, userId) {
  const rows = db
    .prepare("SELECT a.kind AS kind, r.engagement AS e FROM runs r JOIN activities a ON a.id = r.activity_id WHERE r.user_id = ? AND r.engagement IS NOT NULL AND a.kind IS NOT NULL")
    .all(userId);
  const by = {};
  for (const r of rows) (by[r.kind] ??= []).push(r.e);
  const stats = Object.entries(by)
    .map(([kind, list]) => ({ kind, count: list.length, avg: Math.round((list.reduce((s, x) => s + x, 0) / list.length) * 100) / 100 }))
    .filter((s) => s.count >= 2)
    .sort((x, y) => y.avg - x.avg || y.count - x.count);
  return { total: rows.length, best: stats[0] ?? null, stats };
}
