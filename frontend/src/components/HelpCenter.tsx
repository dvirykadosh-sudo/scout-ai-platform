export function HelpCenter() {
  const [q, setQ] = useState("");
  const term = q.trim();
  const rows = term ? FAQ.filter((f) => (f.q + " " + f.a).includes(term)) : FAQ;
  return (
    <>
      <Field label="חיפוש בעזרה" htmlFor="help-q">
        <input id="help-q" type="search" value={q} onChange={(e) => setQ(e.target.value)} />
      </Field>
      <p className="count" role="status">
        {rows.length === 0 ? "לא נמצאו תשובות. אפשר להוסיף בקשה." : `${rows.length} תשובות`}
      </p>
      {rows.map((f) => (
        <details key={f.q} className="card glass insight">
          <summary>{f.q}</summary>
          <p>
            {f.a} {f.href && <Link href={f.href}>{f.link}</Link>}
          </p>
        </details>
      ))}
    </>
  );
}
