"use client";

import { useEffect, useState } from "react";
import { api } from "@/lib/api";
import { PageTitle } from "./ui";

interface Info {
  termsVersion: string;
  retentionDays: number;
  visitorIpMode: "raw" | "hashed";
  passwordMaxAgeDays: number;
}

export function PrivacyPage() {
  const [info, setInfo] = useState<Info | null>(null);
  useEffect(() => {
    api<Info>("/api/privacy-info")
      .then(setInfo)
      .catch(() => {});
  }, []);
  const days = info?.retentionDays ?? 90;
  const hashed = info?.visitorIpMode === "hashed";
  return (
    <>
      <PageTitle lead="מה האתר שומר עליכם, למה, וכמה זמן.">פרטיות ותנאי שימוש</PageTitle>
      <div className="card glass prose">
        <p className="hint">גרסה {info?.termsVersion ?? ""}. הדף הזה מתאר את מה שהאתר עושה בפועל, והמספרים בו נלקחים מהגדרות האתר.</p>

        <h2>מה נשמר</h2>
        <ul className="bullets">
          <li>
            <strong>פרטי חשבון:</strong> שם להצגה, שם משתמש, סיסמה (מוצפנת, לא ניתנת לקריאה), ובמידה שהוספתם גם מייל וטלפון. הם משמשים להתחברות, לאיפוס סיסמה ולהודעות על החשבון.
          </li>
          <li>
            <strong>התכנים שלכם:</strong> פעולות, טיוטות, תיעודי הפעלה והעדפות סגנון, שנשמרים בחשבון שלכם.
          </li>
          <li>
            <strong>כתובת IP וגלישה:</strong> {hashed ? "האתר שומר רק גיבוב של כתובת ה-IP, שלא ניתן להחזיר ממנו את הכתובת, כדי לספור מבקרים ולזהות ניסיונות חדירה." : "האתר שומר את כתובת ה-IP, סוג הדפדפן ושם העמוד, בכל כניסה לחשבון, בניסיון כניסה כושל, ובביקור באתר (פעם אחת לכל 30 דקות)."} המדינה מזוהה לפי הכתובת, בלי מיקום מדויק.
          </li>
          <li>
            <strong>יומן פעולות:</strong> פעולות רגישות (כניסות, שינוי הרשאות, ניהול משתמשים) נרשמות ביומן שאי אפשר לערוך. ברשומות ישנות שנוצרו לפני הגרסה הזו עשויה להופיע כתובת IP, ואין אפשרות למחוק אותן.
          </li>
        </ul>

        <h2>למה</h2>
        <p>לאבטחת האתר: זיהוי כניסות חשודות, חסימת ניסיונות ניחוש סיסמאות, התראה לאדמין על כניסה חריגה, וסטטיסטיקת שימוש כללית. לא נשתמש במידע לפרסום, ולא נמכור או נעביר אותו לגורם חיצוני.</p>

        <h2>כמה זמן</h2>
        <p>
          יומן הכניסות, המבקרים והחיבורים נמחקים אוטומטית אחרי <strong>{days} ימים</strong>.
          {info && info.passwordMaxAgeDays > 0 ? ` סיסמאות פגות אחרי ${info.passwordMaxAgeDays} ימים.` : ""} חשבון שנמחק מוחק גם את התכנים האישיים שלו.
        </p>

        <h2>מי רואה</h2>
        <p>רק מנהלי האתר, לפי תפקידם. מנהל תוכן וצופה בלבד לא רואים כתובות IP ויומני כניסות. כל ייצוא של נתונים נרשם ביומן הפעולות.</p>

        <h2>הזכויות שלכם</h2>
        <ul className="bullets">
          <li>במסך האישי יש כפתור &quot;מחיקת כתובות ה-IP שלי&quot;, שמוחק את הכתובות ששמרנו עליכם ביומן הכניסות ובחיבורים.</li>
          <li>אפשר לבקש מהאדמין לעיין בפרטים ששמורים עליכם, לתקן אותם או למחוק את החשבון.</li>
          <li>אפשר גם לייצא את הפעולות שלכם מהמסך האישי.</li>
        </ul>

        <h2>תנאי שימוש</h2>
        <ul className="bullets">
          <li>האתר מיועד למדריכי שבט מעוז לצורך הכנת פעולות והדרכה. אין להעלות מידע אישי על חניכים.</li>
          <li>אתם אחראים לשמור על הסיסמה שלכם, ולא להעביר אותה לאחרים. מומלץ להפעיל אימות דו-שלבי.</li>
          <li>פעולות שאתם מפרסמים במאגר יכולות להיות מוצגות לכל מדריכי האתר.</li>
          <li>הצעות שהאתר מייצר הן עזר בלבד. האחריות להתאמת הפעולה לקבוצה ולבטיחות היא של המדריך.</li>
          <li>האתר רשאי להשעות חשבון בשימוש לרעה.</li>
        </ul>
        <p className="hint">זהו נוסח כללי שנכתב עבור האתר, ולא ייעוץ משפטי. מומלץ לבקש מגורם משפטי של התנועה לעבור עליו, בעיקר בגלל שהאתר מופעל בידי ארגון נוער.</p>
      </div>
    </>
  );
}
